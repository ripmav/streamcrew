// Command gen seals the built-in app credentials of ADR-0024 into
// internal/appcreds/embedded.go: ML-KEM-768 encapsulation, HKDF-SHA256
// key derivation, and an AES-256-GCM seal of the app record (client ID +
// secret). Run it on the machine of the project owner; the secret is
// read from the environment variable STREAMCREW_APP_SECRET or, if that is
// unset, as one line on stdin — never as a CLI argument (terminal
// history).
//
//	STREAMCREW_APP_SECRET=... go run ./internal/appcreds/gen --client-id <ID>
//
// Commit the rewritten embedded.go to enable the built-in app.
package main

import (
	"bufio"
	"crypto/mlkem"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/ripmav/streamcrew/internal/appcreds"
)

// outName is the generated file below the internal/appcreds package.
const outName = "embedded.go"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	var clientID string
	args := os.Args[1:]
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--client-id":
			if i+1 >= len(args) {
				return errors.New("--client-id needs a value")
			}
			clientID = args[i+1]
			i++
		default:
			return fmt.Errorf("unknown argument %q", args[i])
		}
	}
	if clientID == "" {
		return errors.New("give --client-id")
	}
	secret, err := readSecret()
	if err != nil {
		return err
	}

	// Seal the record: a fresh ML-KEM-768 key pair per run, so every
	// embedded.go carries its own shared secret (ADR-0024).
	dk, err := mlkem.GenerateKey768()
	if err != nil {
		return err
	}
	ss, ct := dk.EncapsulationKey().Encapsulate()
	record, err := appcreds.SealedRecord(clientID, secret)
	if err != nil {
		return err
	}
	nonce, payload, err := appcreds.Seal(record, ss)
	if err != nil {
		return err
	}

	// go run does not change the working directory to the package,
	// so the target is resolved from the repository root (go.mod).
	root, err := repoRoot()
	if err != nil {
		return err
	}
	target := filepath.Join(root, "internal", "appcreds", outName)
	if err := os.WriteFile(target, render(dk, ct, nonce, payload), 0o600); err != nil {
		return fmt.Errorf("write %s: %w", target, err)
	}
	fmt.Fprintf(os.Stdout, "sealed the app record into %s (client ID %s)\n", target, clientID)
	return nil
}

// readSecret returns the app secret from STREAMCREW_APP_SECRET or, if
// unset, from one line on stdin (never echoed).
func readSecret() (string, error) {
	//nolint:forbidigo // the generator reads the secret from the environment by design (ADR-0024); it is not a core configuration
	if s := os.Getenv("STREAMCREW_APP_SECRET"); s != "" {
		return s, nil
	}
	line, err := bufio.NewReader(os.Stdin).ReadString('\n')
	if err != nil && line == "" {
		return "", errors.New("no secret: set STREAMCREW_APP_SECRET or pipe it on stdin")
	}
	return strings.TrimRight(line, "\r\n"), nil
}

// repoRoot walks up from the working directory to the directory that
// holds the go.mod of the repository.
func repoRoot() (string, error) {
	here, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for dir := here; ; dir = filepath.Dir(dir) {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		if dir == filepath.Dir(dir) {
			return "", fmt.Errorf("no go.mod above %s", here)
		}
	}
}

// render writes the generated embedded.go; the hex is wrapped so the
// diff of a rotation stays readable.
func render(dk *mlkem.DecapsulationKey768, ct, nonce, payload []byte) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by internal/appcreds/gen; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Built-in app record of ADR-0024, sealed with\n")
	b.WriteString("// ML-KEM-768 + HKDF-SHA256 + AES-256-GCM. To rotate the\n")
	b.WriteString("// secret, re-run the generator:\n")
	b.WriteString("//\n")
	b.WriteString("//\tSTREAMCREW_APP_SECRET=... go run ./internal/appcreds/gen --client-id <ID>\n")
	b.WriteString("//\n")
	b.WriteString("package appcreds\n\n")
	b.WriteString("var (\n")
	writeHexVar(&b, "embeddedMLKEMPrivateKeyHex", dk.Bytes())
	writeHexVar(&b, "embeddedMLKEMCiphertextHex", ct)
	writeHexVar(&b, "embeddedGCMNonceHex", nonce)
	writeHexVar(&b, "embeddedPayloadHex", payload)
	b.WriteString(")\n")
	return []byte(b.String())
}

func writeHexVar(b *strings.Builder, name string, data []byte) {
	hexs := hex.EncodeToString(data)
	b.WriteString("\t" + name + " string = `")
	for len(hexs) > 0 {
		if len(hexs) > 76 {
			b.WriteString(hexs[:76] + "` +\n\t\t`")
			hexs = hexs[76:]
		} else {
			b.WriteString(hexs + "`")
			hexs = ""
		}
	}
	b.WriteString("\n")
}
